/**
 * All districts as GeoOption[].
 */
export const DISTRICTS: GeoOption[] = DISTRICT_DATA.map((district) => ({
  id: district.id,
  bn: district.bn,
}));

/**
 * Returns the upazilas belonging to a selected district.
 * The IDs are deterministic and remain stable as long as the data order
 * inside this file is unchanged.
 */
export function upazilasForDistrict(districtId: string): GeoOption[] {
  const district = DISTRICT_DATA.find((item) => item.id === districtId);
  if (!district) return [];

  return district.upazilas.map((bn, index) => ({
    id: `${district.id}-upazila-${index + 1}`,
    bn,
  }));
}

/**
 * Bangla district name by district id.
 */
export function districtBnById(districtId: string): string {
  return DISTRICT_DATA.find((item) => item.id === districtId)?.bn ?? "";
}

/**
 * Bangla upazila name by upazila id.
 */
export function upazilaBnById(upazilaId: string): string {
  for (const district of DISTRICT_DATA) {
    const index = district.upazilas.findIndex(
      (_, i) => `${district.id}-upazila-${i + 1}` === upazilaId,
    );

    if (index !== -1) {
      return district.upazilas[index];
    }
  }

  return "";
}

