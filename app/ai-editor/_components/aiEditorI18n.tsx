function normalizeAiText(value: string): string {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\r?\n/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function translateAiText(
  value: string,
  locale: string | undefined,
  baseL?: (value: string) => string,
): string {
  const raw = String(value ?? "");
  if (!locale || !locale.toLowerCase().startsWith("bn")) return raw;

  const key = normalizeAiText(raw);
  if (AI_EDITOR_BN[key]) return AI_EDITOR_BN[key];

  let match = key.match(/^(\d+)\s+images?$/i);
  if (match) return `${match[1]}টি ছবি`;

  match = key.match(/^(.+) left person$/i);
  if (match) {
    return `${translateAiText(match[1], locale, baseL)} — বাম পাশের ব্যক্তি`;
  }

  match = key.match(/^(.+) right person$/i);
  if (match) {
    return `${translateAiText(match[1], locale, baseL)} — ডান পাশের ব্যক্তি`;
  }

  match = key.match(/^remove (.+)$/i);
  if (match) {
    return `${translateAiText(match[1], locale, baseL)} সরান`;
  }

  match = key.match(/^upload (.+)$/i);
  if (match) {
    return `${translateAiText(match[1], locale, baseL)} আপলোড করুন`;
  }

  match = key.match(/^click or scan qr code to upload \((.+)\)$/i);
  if (match) {
    return `আপলোড করতে ক্লিক করুন অথবা QR কোড স্ক্যান করুন (${match[1]})`;
  }

  match = key.match(/^· (\d+) pages$/i);
  if (match) return `· ${match[1]} পৃষ্ঠা`;

  const translated = baseL ? baseL(raw) : raw;
  if (translated && translated !== raw) {
    const bnCount = (translated.match(/[\u0980-\u09FF]/g) || []).length;
    const latinCount = (translated.match(/[A-Za-z]/g) || []).length;
    const latinTechnical = translated.replace(/AI|PDF|JPG|PNG|WebP/g, "");

    if (
      bnCount > 0 &&
      (latinCount <= 4 || !/[A-Za-z]/.test(latinTechnical))
    ) {
      return translated;
    }
  }

  return raw;
}

export function useAiEditorText() {
  const { locale, L: baseL } = useSohozI18n();
  const t = useCallback(
    (value: string) => translateAiText(value, locale, baseL),
    [locale, baseL],
  );

  return { t, locale };
}

export function AiT({ children }: { children: ReactNode }) {
  const { t } = useAiEditorText();

  if (typeof children !== "string") return <>{children}</>;
  return <>{t(children)}</>;
}
