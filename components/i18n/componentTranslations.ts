function toBengaliDigits(value: string): string {
  return value.replace(/[0-9]/g, (digit) => "০১২৩৪৫৬৭৮৯"[Number(digit)]);
}

function normalizeKey(value: unknown): string {
  return String(value ?? "")
    .replace(/\\r\\n/g, " ")
    .replace(/\\r/g, " ")
    .replace(/\\n/g, " ")
    .replace(/\r?\n/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

const NORMALIZED_BN: Record<string, string> = Object.fromEntries(
  Object.entries(BN).map(([source, translated]) => [normalizeKey(source), translated]),
);

/** Return a component-level translation, or undefined if this table has no match. */
export function translateComponentText(value: unknown): string | undefined {
  const raw = String(value ?? "");
  const key = normalizeKey(raw);
  if (!key) return undefined;

  const exact = NORMALIZED_BN[key];
  if (exact !== undefined) {
    const leading = raw.match(/^\s*/)?.[0] ?? "";
    const trailing = raw.match(/\s*$/)?.[0] ?? "";
    return `${leading}${exact}${trailing}`;
  }

  // Some saved-form previews intentionally abbreviate long questions with "...".
  if (key.endsWith("...")) {
    const prefix = key.slice(0, -3).trim();
    const matchingKey = Object.keys(NORMALIZED_BN)
      .filter((candidate) => candidate.startsWith(prefix))
      .sort((a, b) => a.length - b.length)[0];
    if (matchingKey) return NORMALIZED_BN[matchingKey];
  }

  const qualification = /^qualification\s+(\d+)$/i.exec(key);
  if (qualification) return `যোগ্যতা ${toBengaliDigits(qualification[1])}`;
  const experience = /^experience\s+(\d+)$/i.exec(key);
  if (experience) return `অভিজ্ঞতা ${toBengaliDigits(experience[1])}`;
  const video = /^video\s+(\d+)$/i.exec(key);
  if (video) return `ভিডিও ${toBengaliDigits(video[1])}`;
  const number = /^(\d+)\s+questions?$/i.exec(key);
  if (number) return `${toBengaliDigits(number[1])}টি প্রশ্ন`;

  return undefined;
}
